// Regenerates src/constants/build-info.ts with the current git commit and a
// build timestamp. Run via `npm run build-info` — wired into `postinstall`
// (so a fresh clone has real values) and into `prep` (so every build
// captures the commit it was actually built from).
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

function git(command, fallback) {
  try {
    return execSync(command, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return fallback;
  }
}

const commit = git('git rev-parse HEAD', 'unknown');
const commitShort = git('git rev-parse --short HEAD', 'unknown');
const builtAt = new Date().toISOString();

const outPath = path.join(__dirname, '..', 'src', 'constants', 'build-info.ts');
const contents = `// Generated by scripts/generate-build-info.js at build time — do not edit by hand.
export const BuildInfo: { commit: string; commitShort: string; builtAt: string } = {
  commit: '${commit}',
  commitShort: '${commitShort}',
  builtAt: '${builtAt}',
};
`;

fs.writeFileSync(outPath, contents);
console.log(`build-info: ${commitShort} @ ${builtAt} -> ${path.relative(process.cwd(), outPath)}`);
